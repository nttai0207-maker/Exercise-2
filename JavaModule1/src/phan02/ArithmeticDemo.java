package phan02;

public class ArithmeticDemo {
	public static void main(String[] args) {
    int result = 1 + 2; 
    // result = 3
    result = result - 1; 
    // result = 2
    result = result * 2; 
    // result = 4
    result = result / 2; 
    // result = 2
    result = result + 8; 
    // result = 10
    result = result % 7; 
    // result = 3
    
    System.out.println("final result: " + result);
    //Xuất ra đáp án
}

}
